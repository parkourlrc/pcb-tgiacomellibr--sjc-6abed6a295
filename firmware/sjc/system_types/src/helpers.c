float SJC_Helpers_RealClamp(const float var, const float LimitMin, const float LimitMax)
{
	float ret;

	if (var > LimitMax)
	{
		ret = LimitMax;
	}
	else if (var < LimitMin)
	{
		ret = LimitMin;
	}
	else
	{
		ret = var;
	}

	return ret;
}

#ifndef SJC__BASE__NETWORK_CONFIGS_H_
#define SJC__BASE__NETWORK_CONFIGS_H_

#define NETWORK_BAUD_RATE								( (uint32_t) 115200UL )
#define NETWORK_BASE_ADRESS								( (uint32_t) 30UL )
#define MODBUS_USART_INIT_COUNT							( (uint32_t) 50UL )

#define REG_INPUT_START                 				( (uint16_t) 1001 )
#define REG_HOLDING_START               				( (uint16_t) 1    )

typedef enum {
	DEVICE_INFO_OFFSET 									=   0UL,
	NETWORK_INFO_OFFSET 								=  10UL,
	RUNTIME_INFO_OFFSET 								=  50UL,
	ACTUATOR_INFO_OFFSET 								= 100UL,
	CONTROLLER_INFO_OFFSET 								= 120UL,
	SENSORS_INFO_OFFSET    								= 140UL
} eInputRegisterOffsets_t;

typedef enum {
	// Device info
	REG_INPUT_HW_VERSION								= ( (uint16_t) (  0UL   + DEVICE_INFO_OFFSET ) ),
	REG_INPUT_FW_VERSION								= ( (uint16_t) (  1UL   + DEVICE_INFO_OFFSET ) ),

	// Network parameters 
	REG_INPUT_NETWORK_ADDRESS							= ( (uint16_t) (  0UL  + NETWORK_INFO_OFFSET ) ),
	REG_INPUT_NETWORK_PARITY							= ( (uint16_t) (  1UL  + NETWORK_INFO_OFFSET ) ),
	REG_INPUT_NETWORK_BAUD_RATE							= ( (uint16_t) (  2UL  + NETWORK_INFO_OFFSET ) ),

	// Device runtime info
	REG_INPUT_SYSTEM_UPTIME								= ( (uint16_t) (  0UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_CONTROL_MODE								= ( (uint16_t) (  2UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_CONTROL_ERROR								= ( (uint16_t) (  3UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_CONTROL_REFERENCE							= ( (uint16_t) (  5UL  + RUNTIME_INFO_OFFSET ) ),

	REG_INPUT_ACTUATOR_DISPLACEMENT						= ( (uint16_t) (  7UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_AUX_ENCODER_A_DISPLACEMENT				= ( (uint16_t) (  9UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_AUX_ENCODER_B_DISPLACEMENT				= ( (uint16_t) ( 11UL  + RUNTIME_INFO_OFFSET ) ), 

	REG_INPUT_ACTUATOR_VOLTAGE							= ( (uint16_t) ( 13UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_ACTUATOR_CURRENT							= ( (uint16_t) ( 15UL  + RUNTIME_INFO_OFFSET ) ),

	REG_INPUT_DIGITAL_INPUTS							= ( (uint16_t) ( 17UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_DIGITAL_OUTPUTS							= ( (uint16_t) ( 18UL  + RUNTIME_INFO_OFFSET ) ),

	REG_INPUT_SYSTEM_VOLTAGE							= ( (uint16_t) ( 19UL  + RUNTIME_INFO_OFFSET ) ),
	REG_INPUT_SYSTEM_ERROR_FLAGS						= ( (uint16_t) ( 21UL  + RUNTIME_INFO_OFFSET ) ),
 
	// Actuator parameters 
	REG_INPUT_ACTUATOR_STATE							= ( (uint16_t) (  0UL  + ACTUATOR_INFO_OFFSET ) ),
	REG_INPUT_ACTUATOR_BASE_VOLTAGE						= ( (uint16_t) (  1UL  + ACTUATOR_INFO_OFFSET ) ),
	REG_INPUT_ACTUATOR_LIMITS_VOLTAGE					= ( (uint16_t) (  2UL  + ACTUATOR_INFO_OFFSET ) ),
	REG_INPUT_ACTUATOR_LIMITS_CURRENT					= ( (uint16_t) (  3UL  + ACTUATOR_INFO_OFFSET ) ),
	REG_INPUT_ACTUATOR_LIMITS_SPEED						= ( (uint16_t) (  4UL  + ACTUATOR_INFO_OFFSET ) ),

	// Actuator controller parameters
	REG_INPUT_CONTROLLER_PARAMS_KP						= ( (uint16_t) (  0UL + CONTROLLER_INFO_OFFSET ) ),
	REG_INPUT_CONTROLLER_PARAMS_KI						= ( (uint16_t) (  2UL + CONTROLLER_INFO_OFFSET ) ),
	REG_INPUT_CONTROLLER_PARAMS_KD						= ( (uint16_t) (  4UL + CONTROLLER_INFO_OFFSET ) ),
	REG_INPUT_CONTROLLER_PARAMS_AUX1					= ( (uint16_t) (  6UL + CONTROLLER_INFO_OFFSET ) ),
	REG_INPUT_CONTROLLER_PARAMS_AUX2					= ( (uint16_t) (  8UL + CONTROLLER_INFO_OFFSET ) ),
	REG_INPUT_CONTROLLER_PARAMS_RATE					= ( (uint16_t) ( 10UL + CONTROLLER_INFO_OFFSET ) ),

	// Sensors parameters
	REG_INPUT_ACTUATOR_ENCODER_RESOLUTION_PPR			= ( (uint16_t) (  0UL + SENSORS_INFO_OFFSET ) ),
	REG_INPUT_AUX_A_ENCODER_RESOLUTION_PPR				= ( (uint16_t) (  1UL + SENSORS_INFO_OFFSET ) ),
	REG_INPUT_AUX_B_ENCODER_RESOLUTION_PPR				= ( (uint16_t) (  2UL + SENSORS_INFO_OFFSET ) ),

	REG_INPUT_SIZE										= ( (uint16_t) ( 10UL + SENSORS_INFO_OFFSET) )
} eNetworkInputRegisters_t; 

typedef enum {
	SYSTEM_COMMANDS_OFFSET			 					=   00UL,
	DIGITAL_OUTPUTS_OFFSET			 					=   10UL,
	CONTROLLER_UPDATE_OFFSET 		 					=   20UL,
	ACTUATOR_CONFIGS_UPDATE_OFFSET 	 					=   40UL,
	NETWORK_PARAMETERS_UPDATE_OFFSET 					=   80UL,
	SENSORS_PARAMETERS_UPDATE_OFFSET 					=  100UL,
	CONTROLLER_PARAMETERS_UPDATE_OFFSET 				=  120UL
} eHoldingRegisterOffsets_t;

typedef enum {
	CONTROLLER_UPDATE_MSK 		 						= (1UL << 15),
	DIGITAL_OUTPUTS_UPDATE_MSK							= (1UL << 15),
	ACTUATOR_CONFIGS_UPDATE_MSK 	 					= (1UL << 15),
	NETWORK_PARAMETERS_UPDATE_MSK 						= (1UL << 15),
	SENSORS_PARAMETERS_UPDATE_MSK 						= (1UL << 15),
	CONTROLLER_PARAMETERS_UPDATE_MSK 					= (1UL << 15)
} eHoldingRegisterMasks_t;

typedef enum {
	// System commands
	REG_HOLDING_SYSTEM_REBOOT							= ( (uint16_t) (  0UL + SYSTEM_COMMANDS_OFFSET ) ),

	// Digital outputs update
	REG_HOLDING_DIGITAL_OUTPUTS_STATE_UPDATE			= ( (uint16_t) (  0UL + DIGITAL_OUTPUTS_OFFSET ) ),

	// Actuator controller update
	REG_HOLDING_CONTROLLER_REFERENCE					= ( (uint16_t) (  0UL + CONTROLLER_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_MODE_UPDATE					= ( (uint16_t) (  2UL + CONTROLLER_UPDATE_OFFSET ) ),

	// Actuator configs update
	REG_HOLDING_ACTUATOR_BASE_VOLTAGE					= ( (uint16_t) (  0UL + ACTUATOR_CONFIGS_UPDATE_OFFSET ) ),
	REG_HOLDING_ACTUATOR_LIMITS_CURRENT					= ( (uint16_t) (  1UL + ACTUATOR_CONFIGS_UPDATE_OFFSET ) ),
	REG_HOLDING_ACTUATOR_LIMITS_VOLTAGE					= ( (uint16_t) (  2UL + ACTUATOR_CONFIGS_UPDATE_OFFSET ) ),
	REG_HOLDING_ACTUATOR_LIMITS_SPEED					= ( (uint16_t) (  3UL + ACTUATOR_CONFIGS_UPDATE_OFFSET ) ),
	REG_HOLDING_ACTUATOR_RESERVED						= ( (uint16_t) (  5UL + ACTUATOR_CONFIGS_UPDATE_OFFSET ) ),
	REG_HOLDING_ACTUATOR_SETUP_UPDATE					= ( (uint16_t) (  6UL + ACTUATOR_CONFIGS_UPDATE_OFFSET ) ),

	// Network parameters update
	REG_HOLDING_NETWORK_CONFIG_ADDRESS					= ( (uint16_t) (  0UL + NETWORK_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_NETWORK_CONFIG_PARITY					= ( (uint16_t) (  1UL + NETWORK_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_NETWORK_CONFIG_BAUD_RATE				= ( (uint16_t) (  2UL + NETWORK_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_NETWORK_CONFIG_UPDATE					= ( (uint16_t) (  4UL + NETWORK_PARAMETERS_UPDATE_OFFSET ) ),

	// Sensors parameters update
	REG_HOLDING_ACTUATOR_ENCODER_RESOLUTION_PPR			= ( (uint16_t) (  0UL + SENSORS_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_AUX_ENCODER_A_RESOLUTION_PPR			= ( (uint16_t) (  1UL + SENSORS_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_AUX_ENCODER_B_RESOLUTION_PPR			= ( (uint16_t) (  2UL + SENSORS_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_SENSORS_SETUP_UPDATE					= ( (uint16_t) (  3UL + SENSORS_PARAMETERS_UPDATE_OFFSET ) ),

	// Actuator controller parameters update
	REG_HOLDING_CONTROLLER_PARAMS_KP					= ( (uint16_t) (  0UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_PARAMS_KI					= ( (uint16_t) (  2UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_PARAMS_KD					= ( (uint16_t) (  4UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_PARAMS_AUX1					= ( (uint16_t) (  6UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_PARAMS_AUX2					= ( (uint16_t) (  8UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_PARAMS_RATE					= ( (uint16_t) ( 10UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),
	REG_HOLDING_CONTROLLER_PARAMS_UPDATE				= ( (uint16_t) ( 12UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) ),

	REG_HOLDING_SIZE									= ( (uint16_t) ( 20UL + CONTROLLER_PARAMETERS_UPDATE_OFFSET ) )
} eNetworkHoldingRegisters_t;


#define GET_INPUT_REG_ADDRESS(X)        				( (uint16_t) ( REG_INPUT_START + X ) )
#define GET_HOLDING_REG_ADDRESS(X)      				( (uint16_t) ( REG_HOLDING_START + X ) )

#define GET_REG_TABLE_INDEX(X, OFFS)        			( (uint16_t) ( X - OFFS )   )

#define REG_INPUT_NREGS									( (uint16_t) REG_INPUT_SIZE )
#define REG_HOLDING_NREGS               				( (uint16_t) REG_HOLDING_SIZE )


#endif /* SJC__BASE__NETWORK_CONFIGS_H_ */

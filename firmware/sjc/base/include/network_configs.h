#ifndef SJC__DEFINITIONS__NETWORK_CONFIGS_H_
#define SJC__DEFINITIONS__NETWORK_CONFIGS_H_

#define NETWORK_BAUD_RATE								( (uint32_t) 115200UL )
#define NETWORK_BASE_ADRESS								( (uint32_t) 200UL )
#define MODBUS_USART_INIT_COUNT							( (uint32_t) 50UL )

#define DEVICE_INFO_OFFSET								( (uint32_t) 100UL )
#define NETWORK_INFO_OFFSET								( (uint32_t) (10UL+DEVICE_INFO_OFFSET) )
#define DEVICE_CONFIG_OFFSET							( (uint32_t) 200UL )
#define DEVICE_RUNTIME_OFFSET							( (uint32_t) 0UL )

typedef enum {
	// Device runtime info	
	REG_INPUT_SYSTEM_UPTIME								= ( (uint16_t) 0UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_CONTROL_MODE								= ( (uint16_t) 2UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_CONTROL_ERROR								= ( (uint16_t) 3UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_CONTROL_REFERENCE							= ( (uint16_t) 5UL + DEVICE_RUNTIME_OFFSET ),

	REG_INPUT_ACTUATOR_DISPLACEMENT						= ( (uint16_t) 7UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_AUX_ENCODER_A_DISPLACEMENT				= ( (uint16_t) 9UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_AUX_ENCODER_B_DISPLACEMENT				= ( (uint16_t) 11UL + DEVICE_RUNTIME_OFFSET ),

	REG_INPUT_ACTUATOR_OUTPUT_VOLTAGE					= ( (uint16_t) 13UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_ACTUATOR_CURRENT							= ( (uint16_t) 14UL + DEVICE_RUNTIME_OFFSET ),

	REG_INPUT_DIGITAL_INPUTS							= ( (uint16_t) 15UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_DIGITAL_OUTPUTS							= ( (uint16_t) 16UL + DEVICE_RUNTIME_OFFSET ),

	REG_INPUT_SYSTEM_VOLTAGE							= ( (uint16_t) 17UL + DEVICE_RUNTIME_OFFSET ),
	REG_INPUT_SYSTEM_ERROR_FLAGS						= ( (uint16_t) 18UL + DEVICE_RUNTIME_OFFSET ),
	
	// Device info and network parameters
	REG_INPUT_HW_VERSION								= ( (uint16_t) 0UL + DEVICE_INFO_OFFSET ),
	REG_INPUT_FW_VERSION								= ( (uint16_t) 1UL + DEVICE_INFO_OFFSET ),

	REG_INPUT_NETWORK_ADDRESS							= ( (uint16_t) 0UL + NETWORK_INFO_OFFSET ),
	REG_INPUT_NETWORK_PARITY							= ( (uint16_t) 1UL + NETWORK_INFO_OFFSET ),
	REG_INPUT_NETWORK_BAUD_RATE							= ( (uint16_t) 2UL + NETWORK_INFO_OFFSET ),

	// Actuator parameters
	REG_INPUT_ACTUATOR_STATE							= ( (uint16_t) 0UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_ACTUATOR_BASE_VOLTAGE						= ( (uint16_t) 1UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_ACTUATOR_LIMITS_OUTPUT_VOLTAGE			= ( (uint16_t) 2UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_ACTUATOR_LIMITS_OUTPUT_CURRENT			= ( (uint16_t) 3UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_ACTUATOR_LIMITS_OUTPUT_SPEED				= ( (uint16_t) 4UL + DEVICE_CONFIG_OFFSET ),

	// Actuator controller parameters
	REG_INPUT_CONTROLLER_PARAMS_KP						= ( (uint16_t) 6UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_CONTROLLER_PARAMS_KI						= ( (uint16_t) 8UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_CONTROLLER_PARAMS_KD						= ( (uint16_t) 10UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_CONTROLLER_PARAMS_AUX1					= ( (uint16_t) 12UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_CONTROLLER_PARAMS_AUX2					= ( (uint16_t) 14UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_CONTROLLER_PARAMS_RATE					= ( (uint16_t) 16UL + DEVICE_CONFIG_OFFSET ),

	// Sensors parameters
	REG_INPUT_ACTUATOR_ENCODER_RESOLUTION_PPR			= ( (uint16_t) 18UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_AUX_A_ENCODER_RESOLUTION_PPR				= ( (uint16_t) 19UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_AUX_B_ENCODER_RESOLUTION_PPR				= ( (uint16_t) 20UL + DEVICE_CONFIG_OFFSET ),
	REG_INPUT_SIZE										= ( (uint16_t) (REG_INPUT_AUX_B_ENCODER_RESOLUTION_PPR + 1) )
} eNetworkInputRegisters_t;

typedef enum {
	// Actuator controller update
	REG_HOLDING_CONTROLLER_REFERENCE					= ( (uint16_t) 0UL ),
	REG_HOLDING_CONTROLLER_MODE_UPDATE					= ( (uint16_t) 1UL ),

	// Digital outputs update
	REG_HOLDING_DIGITAL_OUTPUTS_STATE_UPDATE			= ( (uint16_t) 2UL ),

	// Actuator configs update
	REG_HOLDING_ACTUATOR_BASE_VOLTAGE					= ( (uint16_t) 3UL ),
	REG_HOLDING_ACTUATOR_LIMITS_OUTPUT_CURRENT			= ( (uint16_t) 4UL ),
	REG_HOLDING_ACTUATOR_LIMITS_OUTPUT_VOLTAGE			= ( (uint16_t) 5UL ),
	REG_HOLDING_ACTUATOR_LIMITS_OUTPUT_SPEED			= ( (uint16_t) 6UL ),
	REG_HOLDING_ACTUATOR_ENCODER_RESOLUTION_PPR			= ( (uint16_t) 8UL ),
	REG_HOLDING_ACTUATOR_SETUP_UPDATE					= ( (uint16_t) 9UL ),

	// Sensors parameters update
	REG_HOLDING_AUX_ENCODER_A_RESOLUTION_PPR			=  ( (uint16_t) 10UL ),
	REG_HOLDING_AUX_ENCODER_B_RESOLUTION_PPR			=  ( (uint16_t) 11UL ),
	REG_HOLDING_AUX_ENCODERS_SETUP_UPDATE				=  ( (uint16_t) 12UL ),

	// Actuator controller parameters update
	REG_HOLDING_CONTROLLER_PARAMS_KP					= ( (uint16_t) 13UL ),
	REG_HOLDING_CONTROLLER_PARAMS_KI					= ( (uint16_t) 15UL ),
	REG_HOLDING_CONTROLLER_PARAMS_KD					= ( (uint16_t) 17UL ),
	REG_HOLDING_CONTROLLER_PARAMS_AUX1					= ( (uint16_t) 19UL ),
	REG_HOLDING_CONTROLLER_PARAMS_AUX2					= ( (uint16_t) 21UL ),
	REG_HOLDING_CONTROLLER_PARAMS_RATE					= ( (uint16_t) 23UL ),
	REG_HOLDING_CONTROLLER_PARAMS_UPDATE				= ( (uint16_t) 24UL ),

	// Network parameters update
	REG_HOLDING_NETWORK_CONFIG_ADDRESS					= ( (uint16_t) 25UL ),
	REG_HOLDING_NETWORK_CONFIG_BAUD_RATE				= ( (uint16_t) 26UL ),
	REG_HOLDING_NETWORK_CONFIG_PARITY					= ( (uint16_t) 27UL ),
	REG_HOLDING_NETWORK_CONFIG_UPDATE					= ( (uint16_t) 28UL ),

	REG_HOLDING_SIZE									= ( (uint16_t) (REG_HOLDING_NETWORK_CONFIG_UPDATE + 1) )
} eNetworkHoldingRegisters_t;

#define REG_INPUT_START                 				( (uint16_t) 1001 )
#define REG_HOLDING_START               				( (uint16_t) 0001 )

#define REG_INPUT_NREGS									( (uint16_t) REG_INPUT_SIZE )
#define REG_HOLDING_NREGS               				( (uint16_t) REG_HOLDING_SIZE )

#define GET_INPUT_REG_ADDRESS(X)        				( (uint16_t) ( REG_INPUT_START + X )   )
#define GET_HOLDING_REG_ADDRESS(X)      				( (uint16_t) ( REG_HOLDING_START + X ) )

#define GET_INPUT_REG_INDEX(X)        					( (uint16_t) ( X - REG_INPUT_START )   )
#define GET_HOLDING_REG_INDEX(X)      					( (uint16_t) ( X - REG_HOLDING_START ) )

#endif /* SJC__DEFINITIONS__NETWORK_CONFIGS_H_ */

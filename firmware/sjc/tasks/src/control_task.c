void ControlTaskApp(void *argument)
{
	/* USER CODE BEGIN ControlTaskApp */
	uint32_t tick;
	tick = osKernelGetTickCount();

	/* Infinite loop */
	for(;;)
	{
		tick += pdMS_TO_TICKS(100);
		SJC_DigitalInterfaces_ToggleOutputState(SJC_HEARTBEAT_OUTPUT);

		osDelayUntil(tick);
	}
	/* USER CODE END MainTaskApp */
}

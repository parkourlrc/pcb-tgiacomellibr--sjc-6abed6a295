void DigitalTaskApp(void *argument)
{
	/* USER CODE BEGIN MainTaskApp */
	uint32_t tick;
	tick = osKernelGetTickCount();

	SJC_DigitalInterfaces_init();
	/* Infinite loop */
	for(;;)
	{
		tick += pdMS_TO_TICKS(5);
		SJC_DigitalInterfaces_ToggleOutputState(SJC_DIGITAL_OUTPUT_A);
		SJC_DigitalInterfaces_ToggleOutputState(SJC_DIGITAL_OUTPUT_B);
		osDelayUntil(tick);
	}
	/* USER CODE END MainTaskApp */
}
